// Helper to generate realistic barcode and IDs
let unitSeq = 1000;
function createUnit(
  group: BloodGroup,
  component: BloodComponent,
  facilityId: string,
  daysUntilExpiry: number,
  status: BloodInventoryUnit['status'] = 'available',
  testedClear: boolean = true,
  tempAlert: boolean = false,
  donorId?: string | number,
  donorName?: string
): BloodInventoryUnit {
  unitSeq++;
  const now = new Date('2026-09-30T02:00:00Z');
  const collDate = new Date(now.getTime() - 5 * 86400000).toISOString();
  const expDate = new Date(now.getTime() + daysUntilExpiry * 86400000).toISOString();

  return {
    unitId: `UNIT-2026-${unitSeq}`,
    bag_id: unitSeq,
    donor_id: donorId,
    donor_name: donorName,
    bagBarcode: `ISBT128-B${group.replace('-', 'N').replace('+', 'P')}-${unitSeq}`,
    bloodGroup: group,
    component,
    volumeMl: component.includes('Plasma') ? 250 : component.includes('Platelets') ? 300 : 450,
    collectionDate: collDate,
    expirationDate: expDate,
    facilityId,
    storageLocation:
      component.includes('Plasma') || component.includes('Cryo')
        ? 'Deep-Freeze Cryo B-04 (-22°C)'
        : component.includes('Platelets')
        ? 'Platelet Agitator Rack 2 (22°C)'
        : 'Cold Storage Vault Bay A (3.6°C)',
    status,
    testedClear,
    temperatureAlert: tempAlert,
  };
}

